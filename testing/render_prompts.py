"""Generate ``testing/prompts/*.prompt.txt`` from ``common.prompts`` (IMPL-12 §2).

One file per active doc type, carrying the role framing, the injected JSON schema
pulled from the IMPL-01 registry, the extraction rules, and the modality-mode
line. Separate files because each type has a different schema and different field
semantics — a Loss Run's valuation date is not an ACORD's policy effective date —
so one type's prompt can be tuned without risk to the others.

**These are generated, never hand-edited.** The spec's requirement is that they
resolve to the identical rendered prompt as ``common.prompts``, asserted in a
test rather than maintained by discipline. Two hand-kept copies of a prompt
diverge by one character eventually, and prompt drift between training and
inference is the most common cause of post-fine-tuning degradation — invisible in
every training metric.

So: this module writes them, and ``test_prompt_files_match_the_renderer`` fails
the moment a checked-in file stops matching a fresh render. Regenerate with::

    python -m testing.render_prompts --write
"""

from __future__ import annotations

import argparse
import logging
from collections.abc import Iterable
from pathlib import Path

from common.config import lobs_in_family
from common.constants import ACORD_FORMS, ACTIVE_DOC_TYPES
from common.prompts import PROMPT_TEMPLATE_VERSION, render_system_prompt
from common.schemas import CANONICAL_FAMILY

log = logging.getLogger(__name__)

PROMPTS_DIR = Path(__file__).resolve().parent / "prompts"

#: The mode these reference files render. ``ocr_plus_image`` is the primary
#: production mode, and ``noisy_ocr_image`` renders identically to it by design,
#: so one file covers both; the image-only variant differs and is emitted too.
REFERENCE_MODES: tuple[str, ...] = ("ocr_plus_image", "image_only")

def reference_targets() -> list[tuple[str, str | None, str | None]]:
    """Every ``(doc_type, acord_form, lob)`` triple that renders a distinct prompt.

    ACORD gets one file **per form**, not one for the type: 25, 125 and 140 have
    different schemas, so a single acord file pinned to one of them would be a
    reference that misrepresents the other two.

    Policies get one **per registered line of business**, for the same reason and
    with more at stake: a homeowners prompt and an ocean marine prompt carry
    different canonical schemas, and the generic `policy` file proves nothing
    about either. The bare `policy` entry stays — it is what a package policy and
    an unclassified line still render.
    """
    targets: list[tuple[str, str | None, str | None]] = []
    for doc_type in ACTIVE_DOC_TYPES:
        if doc_type == "acord":
            targets += [(doc_type, form, None) for form in sorted(ACORD_FORMS, key=int)]
            continue
        targets.append((doc_type, None, None))
        if doc_type == "policy":
            targets += [(doc_type, None, lob) for lob in lobs_in_family(CANONICAL_FAMILY)]
    return targets


def stem(doc_type: str, acord_form: str | None, lob: str | None = None) -> str:
    if acord_form:
        return f"{doc_type}_{acord_form}"
    return f"{doc_type}_{lob}" if lob else doc_type


def header(doc_type: str, modality_mode: str) -> str:
    """A provenance banner, kept out of the compared body.

    The banner records what produced the file and at which template version, so
    a stale file is identifiable on sight rather than only when a test fails.
    """
    return (
        f"# GENERATED by testing.render_prompts — do not edit.\n"
        f"# doc_type={doc_type} modality_mode={modality_mode} "
        f"prompt_template_version={PROMPT_TEMPLATE_VERSION}\n"
        f"# Regenerate: python -m testing.render_prompts --write\n"
    )


def prompt_path(
    doc_type: str,
    modality_mode: str,
    acord_form: str | None = None,
    root: Path = PROMPTS_DIR,
    lob: str | None = None,
) -> Path:
    suffix = "" if modality_mode == "ocr_plus_image" else f".{modality_mode}"
    return root / f"{stem(doc_type, acord_form, lob)}{suffix}.prompt.txt"


def render(
    doc_type: str, modality_mode: str, acord_form: str | None = None, lob: str | None = None
) -> str:
    """The prompt body exactly as ``common.prompts`` renders it."""
    return render_system_prompt(doc_type, modality_mode, acord_form=acord_form, lob=lob)


def file_contents(
    doc_type: str, modality_mode: str, acord_form: str | None = None, lob: str | None = None
) -> str:
    return (
        header(stem(doc_type, acord_form, lob), modality_mode)
        + "\n"
        + render(doc_type, modality_mode, acord_form, lob)
    )


def body_of(text: str) -> str:
    """Strip the generated banner, leaving the prompt to compare."""
    lines = text.splitlines(keepends=True)
    while lines and lines[0].startswith("#"):
        lines.pop(0)
    if lines and not lines[0].strip():
        lines.pop(0)
    return "".join(lines)


def write_all(root: Path = PROMPTS_DIR) -> list[Path]:
    """Regenerate every reference prompt file."""
    root.mkdir(parents=True, exist_ok=True)
    written = []
    for doc_type, form, lob in reference_targets():
        for mode in REFERENCE_MODES:
            path = prompt_path(doc_type, mode, form, root, lob)
            path.write_text(file_contents(doc_type, mode, form, lob), encoding="utf-8")
            written.append(path)

    # A file left over from a renamed target is a reference nothing regenerates,
    # and the drift check would never look at it.
    expected = {p.name for p in written}
    for stale in sorted(root.glob("*.prompt.txt")):
        if stale.name not in expected:
            stale.unlink()
            log.warning("removed stale reference prompt %s", stale.name)

    log.info("wrote %d reference prompt file(s) to %s", len(written), root)
    return written


def drifted(root: Path = PROMPTS_DIR) -> list[str]:
    """Files whose body no longer matches a fresh render.

    A missing file counts as drift: an absent reference cannot prove anything,
    and treating it as passing would defeat the check.
    """
    problems = []
    expected: set[str] = set()
    for doc_type, form, lob in reference_targets():
        for mode in REFERENCE_MODES:
            path = prompt_path(doc_type, mode, form, root, lob)
            expected.add(path.name)
            if not path.exists():
                problems.append(f"{path.name}: missing")
                continue
            if body_of(path.read_text(encoding="utf-8")) != render(doc_type, mode, form, lob):
                problems.append(f"{path.name}: differs from common.prompts")

    problems += [
        f"{path.name}: stale, nothing regenerates it"
        for path in sorted(root.glob("*.prompt.txt"))
        if path.name not in expected
    ]
    return problems


def main(argv: Iterable[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Render the reference prompt files")
    parser.add_argument("--write", action="store_true", help="regenerate the files")
    parser.add_argument("--root", type=Path, default=PROMPTS_DIR)
    args = parser.parse_args(list(argv) if argv is not None else None)

    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    if args.write:
        for path in write_all(args.root):
            print(path)
        return 0

    problems = drifted(args.root)
    for problem in problems:
        print(problem)
    if problems:
        print("run with --write to regenerate")
    return 1 if problems else 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
